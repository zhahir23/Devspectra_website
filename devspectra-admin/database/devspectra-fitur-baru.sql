-- =====================================================================
-- DevSpectra: tabel baru untuk dashboard admin
-- Database : PostgreSQL di Neon (database "neondb")
-- Dibuat   : 17 Oktober 2026
--
-- Isi file ini:
--   1. attendances    absensi harian anggota (masuk, pulang, izin, sakit)
--   2. user_presence  kapan anggota terakhir aktif, untuk status online/offline
--   3. incomes        catatan pemasukan keuangan
--   4. announcements  pengumuman di halaman Ringkasan
--   5. inquiries      kolom baru assigned_to (anggota yang menangani klien),
--                     dan status 'unread' untuk pesan yang status-nya kosong
--   6. settings       baris 'followers_instagram' untuk angka followers
--
-- Cara menjalankan di DBeaver:
--   1. Klik kanan koneksi Neon, pilih SQL Editor > Open SQL script.
--   2. Tempel seluruh isi file ini.
--   3. Klik tombol "Execute SQL Script" (Alt+X). Jangan Ctrl+Enter,
--      karena Ctrl+Enter hanya menjalankan satu perintah.
--   4. Klik kanan Tables > Refresh. Tabel baru akan muncul.
--
-- Aman dijalankan lebih dari sekali: semua perintah memakai IF NOT EXISTS
-- dan dibungkus satu transaksi, jadi kalau ada yang gagal semuanya batal.
-- Tidak ada data lama yang dihapus. Satu-satunya data lama yang diubah:
-- pesan klien yang status-nya masih kosong (NULL) diisi 'unread'.
--
-- Untuk backend (Spring Boot, ddl-auto=update):
--   Nama tabel dan kolom sudah mengikuti gaya penamaan Hibernate (snake_case).
--   Saat membuat @Entity-nya, samakan nama kolomnya supaya Hibernate tidak
--   menambah kolom ganda. Endpoint yang dipakai dashboard ada di
--   CATATAN-BACKEND.md.
-- =====================================================================

BEGIN;

-- 1. ABSENSI -------------------------------------------------------------
-- Satu baris = satu anggota pada satu tanggal.
-- "Belum absen" artinya belum ada baris untuk tanggal itu.
-- status: HADIR, IZIN, SAKIT, ALPA
CREATE TABLE IF NOT EXISTS attendances (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    work_date     DATE         NOT NULL,
    check_in_at   TIMESTAMP(6),
    check_out_at  TIMESTAMP(6),
    status        VARCHAR(20)  NOT NULL DEFAULT 'HADIR',
    note          VARCHAR(255),
    created_at    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_attendances_user_date UNIQUE (user_id, work_date),
    CONSTRAINT ck_attendances_status CHECK (status IN ('HADIR', 'IZIN', 'SAKIT', 'ALPA')),
    CONSTRAINT ck_attendances_times CHECK (
        check_in_at IS NULL OR check_out_at IS NULL OR check_out_at >= check_in_at
    )
);
CREATE INDEX IF NOT EXISTS idx_attendances_work_date ON attendances (work_date);

-- 2. STATUS ONLINE / OFFLINE ---------------------------------------------
-- Dashboard mengirim "heartbeat" tiap 60 detik selama tab-nya terbuka.
-- Anggota dianggap online kalau last_seen_at kurang dari 2 menit yang lalu.
-- Isi last_seen_at dari backend, jangan dari jam browser.
CREATE TABLE IF NOT EXISTS user_presence (
    user_id       BIGINT       PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    last_seen_at  TIMESTAMP(6) NOT NULL
);

-- 3. PEMASUKAN KEUANGAN ----------------------------------------------------
-- amount dalam rupiah penuh tanpa desimal, contoh 2500000.
-- category: PROYEK, PERAWATAN, LAINNYA
CREATE TABLE IF NOT EXISTS incomes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    received_on  DATE         NOT NULL,
    description  VARCHAR(200) NOT NULL,
    client_name  VARCHAR(150),
    category     VARCHAR(30)  NOT NULL DEFAULT 'PROYEK',
    amount       BIGINT       NOT NULL,
    recorded_by  BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    created_at   TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_incomes_amount CHECK (amount > 0),
    CONSTRAINT ck_incomes_category CHECK (category IN ('PROYEK', 'PERAWATAN', 'LAINNYA'))
);
CREATE INDEX IF NOT EXISTS idx_incomes_received_on ON incomes (received_on);

-- 4. PENGUMUMAN ------------------------------------------------------------
-- Dashboard menampilkan pengumuman aktif yang paling baru.
CREATE TABLE IF NOT EXISTS announcements (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message     TEXT         NOT NULL,
    created_by  BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_announcements_active_created
    ON announcements (is_active, created_at DESC);

-- 5. KLIEN MASUK: siapa yang menangani -------------------------------------
ALTER TABLE inquiries
    ADD COLUMN IF NOT EXISTS assigned_to BIGINT REFERENCES users (id) ON DELETE SET NULL;

-- Entity Inquiry tidak mengisi status saat INSERT (insertable = false), jadi status
-- pesan baru berasal dari nilai default kolom. Database DevSpectra sudah memakai
-- 'unread', dan dashboard memakai kata yang sama (unread, read, replied).
-- Default yang sudah ada tidak diubah. 'unread' hanya dipasang kalau kolomnya
-- belum punya default sama sekali (misalnya database baru buatan Hibernate).
DO $$
BEGIN
    IF (SELECT column_default
          FROM information_schema.columns
         WHERE table_schema = current_schema()
           AND table_name = 'inquiries'
           AND column_name = 'status') IS NULL THEN
        ALTER TABLE inquiries ALTER COLUMN status SET DEFAULT 'unread';
    END IF;
END $$;
UPDATE inquiries SET status = 'unread' WHERE status IS NULL;

-- 6. FOLLOWERS -------------------------------------------------------------
-- Memakai tabel settings yang sudah ada. Angkanya diperbarui lewat dashboard.
INSERT INTO settings (setting_key, setting_value, updated_at)
VALUES ('followers_instagram', '0', CURRENT_TIMESTAMP)
ON CONFLICT (setting_key) DO NOTHING;

COMMIT;
